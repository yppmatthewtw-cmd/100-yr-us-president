# ---------------------------------------------------------------- attach
n_ex=0; n_cur=0; n_fed=0
for T in A["terms"]:
    ig=dt.date.fromisoformat(T["inaug"]); en=dt.date.fromisoformat(T["end"])
    # EASY exits
    ex=[]
    for x in T["transitions"]:
        if x["frm"]!="E": continue
        n_ex+=1
        c=EXIT.get((T["name"],x["own"]))
        if c: n_cur+=1
        ex.append({"cd":x["cd"],"own":x["own"],"anchor":x["anchor"],"to":x["to"],
                   "trigger_date":(c[0] if c else x["own"]),
                   "trigger":(c[1] if c else (x["reason"] or "—")),
                   "detail":(c[2] if c else (x["event"] or "")),
                   "curated":bool(c)})
    T["easy_exits"]=ex
    # Fed turns inside this term's cycle window (incl. the transition window)
    ft=[]
    for d,k,lab,note in FED:
        dd=dt.date.fromisoformat(d)
        cd=(dd-ig).days
        if -130<=cd<=1461 and dd<en:
            ft.append({"cd":cd,"date":d,"kind":k,"label":lab,"note":note,
                       "own_term":dd>=ig})
            n_fed+=1
    T["fed_turns"]=ft

A["fed_table"]=[{"date":d,"kind":k,"label":l,"note":n} for d,k,l,n in FED]
json.dump(A,open(_os.path.join(_DATA,"anchor_r5.json"),"w"),separators=(',',':'),ensure_ascii=False)

